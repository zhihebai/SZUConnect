#!/usr/bin/env python3
"""Generate platform code from shared/ design tokens, Chinese copy and icons.

    python3 tools/generate_shared.py          # write generated files
    python3 tools/generate_shared.py --check  # fail if generated files are stale,
                                              # or if code/fixtures use unknown copy keys

Outputs (checked in, never edited by hand):
  macos/SZUConnect/Sources/Generated/SharedCopy.swift
  macos/SZUConnect/Sources/Generated/SharedTokens.swift
  macos/SZUConnect/Sources/Generated/SharedIcons.swift      (when shared/icons exists)
  windows/SZUConnect/core/generated/shared_copy.cpp / .hpp
  windows/SZUConnect/core/generated/shared_tokens.hpp
  windows/SZUConnect/core/generated/shared_icons.cpp / .hpp (when shared/icons exists)

Project link metadata is emitted into the existing SharedCopy.swift/shared_copy.hpp.
"""
import json
import pathlib
import re
import sys
from urllib.parse import urlsplit

ROOT = pathlib.Path(__file__).resolve().parents[1]
SHARED = ROOT / "shared"
MAC_OUT = ROOT / "macos/SZUConnect/Sources/Generated"
WIN_OUT = ROOT / "windows/SZUConnect/core/generated"
HEADER = "GENERATED by tools/generate_shared.py from shared/. Do not edit by hand."


def flatten(node, prefix=""):
    out = {}
    for key, value in node.items():
        if key.startswith("_"):
            continue
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict) and not (set(value) <= {"mac", "windows"} and value):
            out.update(flatten(value, path))
        else:
            out[path] = value
    return out


def variant(value, platform):
    if isinstance(value, dict):
        return value[platform]
    return value


def swift_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def cpp_string(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ord(ch) < 0x20:
            out.append(f"\\x{ord(ch):02x}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def load_icons():
    folder = SHARED / "icons"
    icons = {}
    if not folder.exists():
        return icons
    for svg in sorted(folder.glob("*.svg")):
        text = svg.read_text("utf-8")
        paths = re.findall(r'<path[^>]*\sd="([^"]+)"', text)
        data = " ".join(paths)
        if re.search(r"[^MLCZ0-9 .,\-]", data):
            raise SystemExit(f"{svg.name}: icon paths must be normalized to absolute M/L/C/Z")
        icons[svg.stem] = data
    return icons


def camel(name):
    parts = re.split(r"[-_]", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def hex_to_rgba(value):
    value = value.lstrip("#")
    if len(value) == 6:
        value += "FF"
    return int(value, 16)


def validate_project_url(url):
    """Allow one canonical HTTPS GitHub repository link, without redirect parameters."""
    if not isinstance(url, str) or any(ord(ch) <= 0x20 or ord(ch) == 0x7F for ch in url):
        raise ValueError("Project URL must be a canonical HTTPS GitHub repository link")
    parts = urlsplit(url)
    if (parts.scheme != "https" or parts.netloc != "github.com"
            or parts.query or parts.fragment
            or url != f"https://github.com{parts.path}"
            or not re.fullmatch(r"/[A-Za-z0-9][A-Za-z0-9-]*/[A-Za-z0-9][A-Za-z0-9_.-]*", parts.path)):
        raise ValueError("Project URL must be a canonical HTTPS GitHub repository link")
    return url


def generate():
    copy = json.loads((SHARED / "copy.zh-CN.json").read_text("utf-8"))
    tokens = json.loads((SHARED / "design-tokens.json").read_text("utf-8"))
    links = json.loads((SHARED / "links.json").read_text("utf-8"))
    project_url = validate_project_url(links["project"]["url"])
    flat = flatten(copy)
    icons = load_icons()
    files = {}
    # Platform nouns are shared literals, not runtime inputs. Expand them once for both UIs.
    def platform_copy(value, platform):
        text = variant(value, platform)
        for name, key in {"store": "app.store", "tray": "app.tray", "launch": "app.launchItem"}.items():
            text = text.replace("{" + name + "}", variant(flat[key], platform))
        return text
    # Views use both SVG filenames (shield-check) and token names (shieldCheck).
    # Keep aliases deterministic so either platform draws the same actual path.
    icon_aliases = {alias: data for name, data in icons.items() for alias in {name, camel(name)}}

    # ---------------- Swift ----------------
    lines = [f"// {HEADER}", "import Foundation", "",
             "/// Shared zh-CN copy (shared/copy.zh-CN.json). Look up by dotted key.",
             "enum SharedCopy {", "    static let table: [String: String] = ["]
    for key in sorted(flat):
        lines.append(f"        {swift_string(key)}: {swift_string(platform_copy(flat[key], 'mac'))},")
    lines += ["    ]", "",
              "    /// Returns the text for a key; unknown keys return the key itself so a gap is visible, never blank.",
              "    static func t(_ key: String) -> String { table[key] ?? key }", "",
              "    /// Replaces {name} placeholders. Values are inserted verbatim (never re-interpreted as keys).",
              "    static func f(_ key: String, _ values: [String: String]) -> String {",
              "        var text = t(key)",
              "        for (name, value) in values { text = text.replacingOccurrences(of: \"{\" + name + \"}\", with: value) }",
              "        return text", "    }", "}", "",
              "/// Project link generated from shared/links.json.",
              "enum SharedLinks {",
              f"    static let projectURL = {swift_string(project_url)}", "}", ""]
    files[MAC_OUT / "SharedCopy.swift"] = "\n".join(lines)

    colors = tokens["color"]
    lines = [f"// {HEADER}", "import SwiftUI", "#if os(macOS)", "import AppKit", "#else", "import UIKit", "#endif", "",
             "/// Shared design tokens (shared/design-tokens.json).", "enum SharedTokens {",
             "    struct RGBA: Equatable, Sendable { let r: Double; let g: Double; let b: Double; let a: Double }",
             "    struct Pair: Sendable { let light: RGBA; let dark: RGBA }"]
    lines.append("    static let colors: [String: Pair] = [")
    for name in sorted(colors):
        pair = colors[name]
        def rgba(value):
            v = hex_to_rgba(value)
            return f"RGBA(r: {((v >> 24) & 255) / 255:.4f}, g: {((v >> 16) & 255) / 255:.4f}, b: {((v >> 8) & 255) / 255:.4f}, a: {(v & 255) / 255:.4f})"
        lines.append(f"        {swift_string(name)}: Pair(light: {rgba(pair['light'])}, dark: {rgba(pair['dark'])}),")
    lines.append("    ]")
    for group in ("space", "radius", "size"):
        for name, value in tokens[group].items():
            lines.append(f"    static let {group}{name[:1].upper()}{name[1:]}: CGFloat = {value}")
    for name, spec in tokens["font"].items():
        if isinstance(spec, dict) and "size" in spec:
            lines.append(f"    static let font{name[:1].upper()}{name[1:]}Size: CGFloat = {spec['size']}")
            lines.append(f"    static let font{name[:1].upper()}{name[1:]}Weight: Int = {spec['weight']}")
    lines.append(f"    static let fontLineHeight: CGFloat = {tokens['font']['lineHeight']}")
    for name, value in tokens["motion"].items():
        lines.append(f"    static let motion{name[:1].upper()}{name[1:]}: Double = {value / 1000:.3f}")
    lines.append("    static let tones: [String: (foreground: String, surface: String, icon: String)] = [")
    for name, spec in tokens["tone"].items():
        lines.append(f"        {swift_string(name)}: ({swift_string(spec['foreground'])}, {swift_string(spec['surface'])}, {swift_string(spec['icon'])}),")
    lines += ["    ]", "}", ""]
    files[MAC_OUT / "SharedTokens.swift"] = "\n".join(lines)

    if icons:
        lines = [f"// {HEADER}", "import Foundation", "",
                 "/// Normalized 24x24 stroke icon paths (absolute M/L/C/Z only) from shared/icons/*.svg.",
                 "enum SharedIcons {", "    static let paths: [String: String] = ["]
        for name in sorted(icon_aliases):
            lines.append(f"        {swift_string(name)}: {swift_string(icon_aliases[name])},")
        lines += ["    ]", "}", ""]
        files[MAC_OUT / "SharedIcons.swift"] = "\n".join(lines)

    # ---------------- C++ ----------------
    files[WIN_OUT / "shared_copy.hpp"] = "\n".join([
        f"// {HEADER}", "#pragma once", "#include <string>", "#include <string_view>", "#include <utility>", "#include <vector>", "",
        "namespace szu::copy {", "// UTF-8 text for a dotted key; unknown keys return the key itself (visible, never blank).",
        "std::string_view text(std::string_view key);", "bool contains(std::string_view key);",
        "// Replaces {name} placeholders with the given UTF-8 values.",
        "std::string format(std::string_view key, const std::vector<std::pair<std::string_view, std::string>>& values);",
        "std::size_t size();", "}  // namespace szu::copy", "",
        "namespace szu::links {",
        "// Project link generated from shared/links.json.",
        f"inline constexpr std::string_view kProjectUrl = {cpp_string(project_url)};",
        "}  // namespace szu::links", ""])
    lines = [f"// {HEADER}", '#include "shared_copy.hpp"', "#include <algorithm>", "#include <array>", "",
             "namespace szu::copy {", "namespace {", "struct Entry { std::string_view key; std::string_view value; };",
             f"constexpr std::array<Entry, {len(flat)}> kEntries = {{{{"]
    for key in sorted(flat):
        lines.append(f"    Entry{{{cpp_string(key)}, {cpp_string(platform_copy(flat[key], 'windows'))}}},")
    lines += ["}};", "const Entry* find(std::string_view key) {",
              "    auto it = std::lower_bound(kEntries.begin(), kEntries.end(), key,",
              "                               [](const Entry& e, std::string_view k) { return e.key < k; });",
              "    return (it != kEntries.end() && it->key == key) ? &*it : nullptr;", "}", "}  // namespace", "",
              "std::string_view text(std::string_view key) { const Entry* e = find(key); return e ? e->value : key; }",
              "bool contains(std::string_view key) { return find(key) != nullptr; }",
              f"std::size_t size() {{ return kEntries.size(); }}",
              "std::string format(std::string_view key, const std::vector<std::pair<std::string_view, std::string>>& values) {",
              "    std::string out(text(key));",
              "    for (const auto& [name, value] : values) {",
              "        const std::string token = \"{\" + std::string(name) + \"}\";",
              "        for (std::size_t at = out.find(token); at != std::string::npos; at = out.find(token, at + value.size())) {",
              "            out.replace(at, token.size(), value);", "        }", "    }", "    return out;", "}",
              "}  // namespace szu::copy", ""]
    files[WIN_OUT / "shared_copy.cpp"] = "\n".join(lines)

    lines = [f"// {HEADER}", "#pragma once", "#include <cstdint>", "#include <string_view>", "", "namespace szu::tokens {",
             "struct ColorPair { std::string_view name; std::uint32_t light; std::uint32_t dark; };  // 0xRRGGBBAA",
             f"inline constexpr ColorPair kColors[] = {{"]
    for name in sorted(colors):
        lines.append(f"    {{{cpp_string(name)}, 0x{hex_to_rgba(colors[name]['light']):08X}u, 0x{hex_to_rgba(colors[name]['dark']):08X}u}},")
    lines.append("};")
    for group in ("space", "radius", "size"):
        for name, value in tokens[group].items():
            lines.append(f"inline constexpr float k{group[:1].upper()}{group[1:]}{name[:1].upper()}{name[1:]} = {float(value)}f;")
    for name, spec in tokens["font"].items():
        if isinstance(spec, dict) and "size" in spec:
            lines.append(f"inline constexpr float kFont{name[:1].upper()}{name[1:]}Size = {float(spec['size'])}f;")
            lines.append(f"inline constexpr int kFont{name[:1].upper()}{name[1:]}Weight = {spec['weight']};")
    lines.append(f"inline constexpr float kFontLineHeight = {tokens['font']['lineHeight']}f;")
    families = tokens["font"]["family"]["windows"]
    lines.append("inline constexpr std::string_view kFontFamilies[] = {" + ", ".join(cpp_string(f) for f in families) + "};")
    for name, value in tokens["motion"].items():
        lines.append(f"inline constexpr int kMotion{name[:1].upper()}{name[1:]} = {value};")
    lines.append("struct Tone { std::string_view name; std::string_view foreground; std::string_view surface; std::string_view icon; };")
    lines.append("inline constexpr Tone kTones[] = {")
    for name, spec in tokens["tone"].items():
        lines.append(f"    {{{cpp_string(name)}, {cpp_string(spec['foreground'])}, {cpp_string(spec['surface'])}, {cpp_string(spec['icon'])}}},")
    lines += ["};", "}  // namespace szu::tokens", ""]
    files[WIN_OUT / "shared_tokens.hpp"] = "\n".join(lines)

    if icons:
        files[WIN_OUT / "shared_icons.hpp"] = "\n".join([
            f"// {HEADER}", "#pragma once", "#include <string_view>", "", "namespace szu::icons {",
            "// Normalized 24x24 stroke paths (absolute M/L/C/Z); empty view when unknown.",
            "std::string_view path(std::string_view name);", "}  // namespace szu::icons", ""])
        lines = [f"// {HEADER}", '#include "shared_icons.hpp"', "#include <algorithm>", "#include <array>", "",
                 "namespace szu::icons {", "namespace { struct Entry { std::string_view name; std::string_view data; };",
                 f"constexpr std::array<Entry, {len(icon_aliases)}> kIcons = {{{{"]
        for name in sorted(icon_aliases):
            lines.append(f"    Entry{{{cpp_string(name)}, {cpp_string(icon_aliases[name])}}},")
        lines += ["}}; }  // namespace",
                  "std::string_view path(std::string_view name) {",
                  "    auto it = std::lower_bound(kIcons.begin(), kIcons.end(), name, [](const Entry& e, std::string_view n) { return e.name < n; });",
                  "    return (it != kIcons.end() && it->name == name) ? it->data : std::string_view{};", "}",
                  "}  // namespace szu::icons", ""]
        files[WIN_OUT / "shared_icons.cpp"] = "\n".join(lines)
    return files, flat


KEY_PATTERNS = [re.compile(r'SharedCopy\.[tf]\(\s*"([A-Za-z0-9_.]+)"'), re.compile(r'\b[TUF]\(\s*"([A-Za-z0-9_.]+)"'),
                re.compile(r'copy::(?:text|format)\(\s*"([A-Za-z0-9_.]+)"'),
                re.compile(r'\btext\(\s*"([a-z][A-Za-z0-9]*\.[A-Za-z0-9_.]+)"\s*\)'),
                re.compile(r'\b(?:L|Lf)\(\s*"([A-Za-z0-9_.]+)"')]


def used_keys():
    found = {}
    for folder in (ROOT / "macos/SZUConnect/Sources", ROOT / "windows/SZUConnect"):
        if not folder.exists():
            continue
        for path in folder.rglob("*"):
            if (path.suffix not in (".swift", ".cpp", ".hpp", ".h") or "generated" in path.parts or "Generated" in path.parts
                    or "tests" in path.parts or "Tests" in path.parts):
                continue
            text = path.read_text("utf-8", errors="replace")
            for pattern in KEY_PATTERNS:
                for match in pattern.finditer(text):
                    if match.group(1).endswith("."):
                        continue  # dynamic key built at runtime, e.g. "mode." + name + ".title"
                    found.setdefault(match.group(1), path.relative_to(ROOT))
    return found


def fixture_keys():
    keys = set()
    data = json.loads((SHARED / "status-fixtures.json").read_text("utf-8"))
    for case in data["cases"]:
        e = case["expected"]
        keys.update([e["headline"], e["detail"], e["chip"]])
        keys.update(f"action.{a}" for a in (e["primary"], e["secondary"]) if a)
        if e["banner"]:
            keys.update([e["banner"]["key"] + ".title", e["banner"]["key"] + ".detail"])
    compat = json.loads((SHARED / "fixtures/compat-diagnosis-cases.json").read_text("utf-8"))
    for case in compat["cases"]:
        keys.add(f"compat.verdict.{case['expected']['verdict']}.title")
        keys.update(f"compat.rec.{r}" for r in case["expected"]["recommendations"])
    return keys


def main():
    check = "--check" in sys.argv
    files, flat = generate()
    problems = []
    for path, content in files.items():
        if check:
            if not path.exists() or path.read_text("utf-8") != content:
                problems.append(f"stale generated file: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, "utf-8")
            print("wrote", path.relative_to(ROOT))
    for key, where in sorted(used_keys().items()):
        if key not in flat:
            problems.append(f"unknown copy key {key!r} used in {where}")
    for key in sorted(fixture_keys()):
        if key not in flat:
            problems.append(f"unknown copy key {key!r} referenced by shared fixtures")
    print(f"copy keys: {len(flat)}; icons: {len(load_icons())}; problems: {len(problems)}")
    for line in problems:
        print("  -", line)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
